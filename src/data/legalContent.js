/*
  Renvoie le contenu légal pour une langue donnée.
  Si la langue n'est pas traduite (ex: ja, ru, ar...), retombe sur l'anglais.
*/
export function getLegalContent(lang) {
  const code = (lang || 'en').slice(0, 2)
  return legalByLang[code] || legalByLang.en
}

